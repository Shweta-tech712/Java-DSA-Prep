public class PracticeExample01 {
    public static void main( String [] args ) {

        int marks = 80;

        System.out.println("Marks : " + marks);

        System.out.println(" Marks > 50 : " + (marks > 50));
        System.out.println(" Marks < 90 : " + (marks < 90));
        System.out.println(" Marks >= 100 : " + (marks >= 100));
        System.out.println(" Marks <= 55 : " + (marks <= 55));
        System.out.println(" Marks != 80 : " + (marks != 80));
        System.out.println(" Marks == 70 : " + (marks == 70));

    }
}